// Copies the shared contracts (repo-root contracts/*.json) into typed `as const` TypeScript
// modules, so names like stage, error code, level and directive are literal types. Turbopack only
// resolves files inside apps/web, so the app imports these copies; contract tests fail when a
// copy drifts.
//
//   contracts/ingestion.json     → src/lib/ingestion/contract.generated.ts  (export CONTRACT)
//   contracts/answer-format.json → src/lib/answers/format.generated.ts      (export FORMAT)
//
// Runs before `npm run dev` and `npm run build`; run `npm run contract:sync` after editing a JSON.
// `--check` exits 1 instead of writing. No contracts folder (a deploy that only has apps/web) =
// keep the committed copies.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const check = process.argv.includes("--check");
const CONTRACTS = [
  { json: "ingestion.json", ts: "../src/lib/ingestion/contract.generated.ts", name: "CONTRACT" },
  { json: "answer-format.json", ts: "../src/lib/answers/format.generated.ts", name: "FORMAT" },
];

let stale = false;
for (const { json, ts, name } of CONTRACTS) {
  const source = fileURLToPath(new URL(`../../../contracts/${json}`, import.meta.url));
  const target = fileURLToPath(new URL(ts, import.meta.url));
  if (!existsSync(source)) {
    console.log(`sync-contract: no contracts/${json}, keeping the committed copy`);
    continue;
  }
  const contract = JSON.parse(readFileSync(source, "utf8"));
  const next =
    `// Generated by scripts/sync-contract.mjs from contracts/${json}. Do not edit:\n` +
    "// change the JSON, then run `npm run contract:sync`.\n\n" +
    `export const ${name} = ${JSON.stringify(contract, null, 2)} as const;\n`;
  const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current === next) continue;
  if (check) {
    console.error(`sync-contract: ${ts} is out of date. Run \`npm run contract:sync\`.`);
    stale = true;
    continue;
  }
  writeFileSync(target, next);
  console.log(`sync-contract: ${ts.replace("../", "")} updated`);
}
if (stale) process.exit(1);
