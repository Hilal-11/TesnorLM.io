// Copies the shared ingestion contract (repo-root contracts/ingestion.json) into
// src/lib/ingestion/contract.generated.ts, typed `as const` so stage names and error codes are
// literal types. Turbopack only resolves files inside apps/web, so the app imports this copy;
// src/lib/ingestion/contract.test.ts fails when it is out of date.
//
// Runs before `npm run dev` and `npm run build`; run `npm run contract:sync` after editing the
// JSON. `--check` exits 1 instead of writing. No contracts folder (a deploy that only has
// apps/web) = keep the committed copy.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(new URL("../../../contracts/ingestion.json", import.meta.url));
const target = fileURLToPath(
  new URL("../src/lib/ingestion/contract.generated.ts", import.meta.url),
);
const check = process.argv.includes("--check");

if (!existsSync(source)) {
  console.log("sync-contract: no contracts/ingestion.json, keeping the committed copy");
  process.exit(0);
}

const contract = JSON.parse(readFileSync(source, "utf8"));
const next =
  "// Generated by scripts/sync-contract.mjs from contracts/ingestion.json. Do not edit:\n" +
  "// change the JSON, then run `npm run contract:sync`.\n\n" +
  `export const CONTRACT = ${JSON.stringify(contract, null, 2)} as const;\n`;
const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";

if (current === next) process.exit(0);
if (check) {
  console.error(
    "sync-contract: contract.generated.ts is out of date. Run `npm run contract:sync`.",
  );
  process.exit(1);
}
writeFileSync(target, next);
console.log("sync-contract: src/lib/ingestion/contract.generated.ts updated");
